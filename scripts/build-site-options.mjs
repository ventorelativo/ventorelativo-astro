#!/usr/bin/env node
/**
 * Writes `src/lib/siteOptions.ts` from the flight sites themselves.
 *
 * `keystatic.config.ts` needs the fourteen sites as label/value pairs, because
 * Keystatic's relationship field renders `<Item>{item.slug}</Item>`: it would
 * offer an editor "pian-dellalpe" where they are looking for "Pian dell'Alpe".
 * A select takes a label and a value and solves that, at the cost of a list.
 *
 * This is that list, generated, so renaming a site or adding one is a content
 * change and nothing else. The config is bundled for the browser and cannot
 * read the filesystem, which is why this runs first and leaves a file behind.
 *
 * Committed, not ignored: `astro check` runs before the build in `npm run
 * verify`, and an import of a file that does not exist yet fails it. `prebuild`
 * and `predev` regenerate it, so a stale copy cannot survive a build.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const DIR = 'src/content/sites';
const OUT = 'src/lib/siteOptions.ts';

/** The title as YAML meant it: `'Pian dell''Alpe'` is one apostrophe, not two. */
function yamlString(raw) {
  const value = raw.trim();
  if (/^'.*'$/.test(value)) return value.slice(1, -1).replaceAll("''", "'");
  if (/^".*"$/.test(value)) return value.slice(1, -1).replaceAll('\\"', '"');
  return value;
}

/**
 * A string literal Prettier would leave alone.
 *
 * `JSON.stringify` always emits double quotes, which the repository's Prettier
 * config rewrites to single: the generated file then failed `format:check` on
 * every run, in a file nobody is meant to edit. Prettier picks whichever quote
 * needs fewer escapes, single on a tie, so "Pian dell'Alpe" keeps its doubles.
 */
function tsString(value) {
  const singles = (value.match(/'/g) ?? []).length;
  const doubles = (value.match(/"/g) ?? []).length;
  return singles > doubles
    ? JSON.stringify(value)
    : `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

const sites = [];
for (const file of await readdir(DIR)) {
  if (!file.endsWith('.mdx')) continue;
  const title = (await readFile(join(DIR, file), 'utf8')).match(/^title:\s*(.+)$/m);
  if (!title) throw new Error(`${join(DIR, file)} has no title.`);
  sites.push({ label: yamlString(title[1]), value: file.replace(/\.mdx$/, '') });
}

sites.sort((a, b) => a.label.localeCompare(b.label, 'it'));

const body = `/**
 * The flight sites, for the "Sito di volo" picker in \`keystatic.config.ts\`.
 *
 * GENERATED by scripts/build-site-options.mjs. Do not edit: add, rename or
 * remove a site in src/content/sites and the next build rewrites this.
 */
export const SITE_OPTIONS = [
${sites.map((s) => `  { label: ${tsString(s.label)}, value: ${tsString(s.value)} },`).join('\n')}
] as const;
`;

await writeFile(OUT, body);
console.log(`site options ok: ${sites.length} sites`);
